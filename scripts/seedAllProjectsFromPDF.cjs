async function seed() {
  console.log(`Iniciando carga de ${rawProjects.length} proyectos históricos de Pastoral Social...`);

  let count = 0;
  for (let i = 0; i < rawProjects.length; i++) {
    const p = rawProjects[i];
    const coords = getCoords(p.municipality, i);

    const docId = `proj_ps_${p.year}_${String(i + 1).padStart(3, '0')}`;
    const pointRef = doc(db, 'points', docId);

    const data = {
      id: docId,
      title: p.title,
      description: p.objectives || p.title,
      municipality: p.municipality,
      communityOrVereda: p.communityOrVereda || '',
      lat: coords.lat,
      lng: coords.lng,
      year: p.year,
      endYear: p.endYear || undefined,
      executionPeriod: p.executionPeriod || `${p.year}`,
      fundingAgency: p.fundingAgency || 'Pastoral Social Florencia',
      targetPopulation: p.targetPopulation || 'Comunidades de la Diócesis de Florencia',
      objectives: p.objectives || '',
      resultsOrAchievements: p.resultsOrAchievements || '',
      categoryId: p.categoryId,
      status: p.year >= 2025 ? 'active' : 'historical',
      populationTypes: [p.targetPopulation?.split(',')[0] || 'Comunidad en Territorio'],
      beneficiariesApprox: p.beneficiariesApprox || undefined,
      keyActions: p.resultsOrAchievements
        ? p.resultsOrAchievements
            .split(/[;.]/)
            .map((s) => s.trim())
            .filter((s) => s.length > 5 && s.length < 90)
            .slice(0, 4)
        : [],
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString(),
    };

    // Clean undefined fields for Firestore
    const cleanData = {};
    for (const [k, v] of Object.entries(data)) {
      if (v !== undefined) {
        cleanData[k] = v;
      }
    }

    await setDoc(pointRef, cleanData);
    count++;
    console.log(`[${count}/${rawProjects.length}] Guardado: ${p.title.slice(0, 45)}... -> ${p.municipality} (${p.categoryId})`);
  }

  console.log(`\n¡Éxito! Se han guardado ${count} proyectos en Firestore vinculados a las 5 líneas de Pastoral Social Florencia.`);
  process.exit(0);
}

seed().catch((err) => {
  console.error('Error al guardar proyectos:', err);
  process.exit(1);
});

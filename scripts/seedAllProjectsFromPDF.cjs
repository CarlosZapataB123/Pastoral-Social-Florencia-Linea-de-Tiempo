function getCoords(muniName, offsetIndex = 0) {
  const base = MUNIS[muniName] || MUNIS['Florencia'];
  // Dispersión sutil para que no queden exactamente superpuestos
  const angle = (offsetIndex * 137.5 * Math.PI) / 180;
  const radius = 0.015 + ((offsetIndex % 5) * 0.008);
  return {
    lat: Number((base.lat + Math.sin(angle) * radius).toFixed(5)),
    lng: Number((base.lng + Math.cos(angle) * radius).toFixed(5)),
  };
}

